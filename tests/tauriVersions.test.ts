import { describe, expect, test } from 'bun:test';
import { cargoTauriVersions, comparePairs, crateFor, npmTauriVersions } from '../scripts/check-tauri-versions.mjs';

const NPM_LOCK = JSON.stringify({
  name: 'frost',
  lockfileVersion: 3,
  packages: {
    '': { name: 'frost' },
    'node_modules/@tauri-apps/api': { version: '2.12.0' },
    'node_modules/@tauri-apps/cli': { version: '2.12.0' },
    'node_modules/@tauri-apps/plugin-autostart': { version: '2.7.0' },
    'node_modules/@tauri-apps/plugin-dialog': { version: '2.8.0' },
    'node_modules/@tauri-apps/plugin-opener': { version: '2.7.0' },
    'node_modules/some-lib/node_modules/@tauri-apps/api': { version: '1.0.0' },
  },
});

const CARGO_LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "tauri"
version = "2.12.1"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "tauri-build"
version = "2.5.0"

[[package]]
name = "tauri-plugin-autostart"
version = "2.5.1"

[[package]]
name = "tauri-plugin-dialog"
version = "2.8.1"
dependencies = [
 "log",
]

[[package]]
name = "tauri-plugin-fs"
version = "2.6.0"

[[package]]
name = "tauri-plugin-opener"
version = "2.7.0"
`;

describe('версии Tauri: Rust ↔ npm', () => {
  test('npm: только пакеты @tauri-apps верхнего уровня', () => {
    const npm = npmTauriVersions(NPM_LOCK);
    expect(npm.get('@tauri-apps/api')).toBe('2.12.0');
    expect(npm.get('@tauri-apps/plugin-dialog')).toBe('2.8.0');
    expect(npm.size).toBe(5);
  });

  test('Cargo.lock: tauri и tauri-plugin-*, без tauri-build', () => {
    const cargo = cargoTauriVersions(CARGO_LOCK);
    expect(cargo.get('tauri')).toEqual(['2.12.1']);
    expect(cargo.get('tauri-plugin-dialog')).toEqual(['2.8.1']);
    expect(cargo.has('tauri-build')).toBe(false);
  });

  test('пары: api ↔ tauri, plugin-x ↔ tauri-plugin-x, у cli пары нет', () => {
    expect(crateFor('@tauri-apps/api')).toBe('tauri');
    expect(crateFor('@tauri-apps/plugin-global-shortcut')).toBe('tauri-plugin-global-shortcut');
    expect(crateFor('@tauri-apps/cli')).toBeNull();
  });

  test('ловит разъехавшийся плагин (как autostart 2.7 против 2.5), патчи не мешают', () => {
    const rows = comparePairs(npmTauriVersions(NPM_LOCK), cargoTauriVersions(CARGO_LOCK));
    const bad = rows.filter((r: { ok: boolean }) => !r.ok).map((r: { crate: string }) => r.crate);
    expect(bad).toEqual(['tauri-plugin-autostart']);
    // tauri-plugin-fs есть только в Rust (зависимость dialog): не ошибка
    expect(rows.some((r: { crate: string }) => r.crate === 'tauri-plugin-fs')).toBe(false);
    expect(rows.length).toBe(4);
  });

  test('плагин только в package.json: ошибка', () => {
    const npm = new Map([['@tauri-apps/plugin-clipboard-manager', '2.3.0']]);
    const rows = comparePairs(npm, cargoTauriVersions(CARGO_LOCK));
    expect(rows[0].ok).toBe(false);
  });

  test('две версии одного крейта: обе должны совпасть', () => {
    const cargo = new Map([['tauri-plugin-opener', ['2.7.0', '2.6.3']]]);
    const rows = comparePairs(new Map([['@tauri-apps/plugin-opener', '2.7.0']]), cargo);
    expect(rows[0].ok).toBe(false);
  });
});
